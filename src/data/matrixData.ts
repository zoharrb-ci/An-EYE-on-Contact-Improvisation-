type RawParamTuple = [
  titleHe: string,
  titleEn: string,
  underHe: string,
  underEn: string,
  flowHe: string,
  flowEn: string,
  overHe: string,
  overEn: string,
  promptHe: string,
  promptEn: string,
  scoreId?: GuidedScoreId,
];

function buildAxisParams(axisId: ReflectionAxisId, rows: RawParamTuple[]): MatrixParameter[] {
  return rows.map((row, idx) => ({
    id: `${axisId}-${String(idx + 1).padStart(2, '0')}`,
    axisId,
    index: idx + 1,
    title: { he: row[0], en: row[1] },
    underDesc: { he: row[2], en: row[3] },
    flowDesc: { he: row[4], en: row[5] },
    overDesc: { he: row[6], en: row[7] },
    reflectionPrompt: { he: row[8], en: row[9] },
    suggestedScoreId: row[10],
  }));
}

